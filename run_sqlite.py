"""Runs the whole project offline with Python's built-in sqlite3 (no installs, no internet).
Usage:  python run_sqlite.py      -> prints results and writes results/results.md
"""
import csv, os, re, sqlite3

BASE = os.path.dirname(os.path.abspath(__file__))
path = lambda *p: os.path.join(BASE, *p)
con = sqlite3.connect(":memory:")
cur = con.cursor()


def run_script(name):
    with open(path("sql", name), encoding="utf-8") as f:
        return f.read()


def load_csv(table, file, blank_to_null=()):
    with open(path("data", file), encoding="utf-8") as f:
        rows = list(csv.reader(f))
    header, body = rows[0], rows[1:]
    idx = [header.index(c) for c in blank_to_null]
    for r in body:
        for i in idx:
            if r[i] == "":
                r[i] = None
    cur.executemany(f"INSERT INTO {table} ({','.join(header)}) VALUES ({','.join('?' * len(header))})", body)


cur.executescript(run_script("01_schema.sql"))
load_csv("titles", "titles.csv", blank_to_null=("country", "rating"))
load_csv("users", "users.csv")
load_csv("watch_events", "watch_events.csv")
con.commit()


def run_queries(script):
    """Split a script into blocks that start with '-- Q:' and execute the statements in them."""
    out = []
    blocks = re.split(r"(?m)^-- Q: ", script)
    prefix = blocks[0]
    for b in blocks[1:]:
        label, _, sql = b.partition("\n")
        out.append((label.strip(), sql))
    return prefix, out


report = ["# Query results (generated by run_sqlite.py)\n",
          "> Data is **synthetic** (see README). Numbers show how the queries work, not real-world facts.\n"]

for script_name in ("02_data_quality_and_cleaning.sql", "03_analysis.sql"):
    _, blocks = run_queries(run_script(script_name))
    # statements that must run first in the cleaning script (view creation) are inside the last block
    for label, sql in blocks:
        statements = [s.strip() for s in sql.split(";") if s.strip() and not all(
            line.strip().startswith("--") or not line.strip() for line in s.splitlines())]
        for stmt in statements:
            cur.execute(stmt)
            if cur.description:
                cols = [d[0] for d in cur.description]
                rows = cur.fetchall()
                report.append(f"\n## {label}\n")
                report.append("| " + " | ".join(cols) + " |")
                report.append("|" + "---|" * len(cols))
                for r in rows:
                    report.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")

text = "\n".join(report) + "\n"
with open(path("results", "results.md"), "w", encoding="utf-8") as f:
    f.write(text)
print(text)
